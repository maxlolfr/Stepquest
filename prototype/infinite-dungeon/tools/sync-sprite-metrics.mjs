// Regenerates js/data/sprite-metrics.js from Dragonbound II (read only, never written).
// Usage, from prototype/infinite-dungeon/:  node tools/sync-sprite-metrics.mjs
// Copies two tables of prototype/dragonbound2/index.html:
//   POSEM: per image [height factor, horizontal anchor] used to stand a sprite on the floor
//   ANIM:  animated hero frames per action
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = readFileSync(path.join(here, '../../dragonbound2/index.html'), 'utf8');
const grab = name => {
  const m = new RegExp(`^const ${name} = (\\{.*?\\});`, 'm').exec(src);
  if (!m) throw new Error(`${name} not found in dragonbound2/index.html`);
  return JSON.parse(m[1]);
};
const version = (/^const VERSION = '([^']+)'/m.exec(src) || [])[1] || 'unknown';
const posem = grab('POSEM'), anim = grab('ANIM');
const out = `// GENERATED by tools/sync-sprite-metrics.mjs — do not edit by hand.
// Source: prototype/dragonbound2/index.html (${version}).
// POSEM[key] = [height factor, anchor x (0 left … 1 right)] for img key.webp
export const POSEM = ${JSON.stringify(posem)};
// ANIM[heroBase][action] = frame count, files ${'${base}'}A_${'${action}${i}'}.webp
export const ANIM = ${JSON.stringify(anim)};
`;
writeFileSync(path.join(here, '../js/data/sprite-metrics.js'), out);
console.log(`sprite-metrics.js: ${Object.keys(posem).length} images, ${Object.keys(anim).length} animated heroes (${version})`);
