// Regenerates js/data/db2-data.js from Dragonbound II (read only, never written).
// Usage, from prototype/infinite-dungeon/:  node tools/sync-db2-data.mjs
// Copies: MON (monster names, stats, traits, weaknesses), CHAPTERS (names, bosses)
// and LEVELS (level names, backgrounds, horizon line). Only data literals are
// evaluated, in an empty sandbox.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = readFileSync(path.join(here, '../../dragonbound2/index.html'), 'utf8');
const version = (/^const VERSION = '([^']+)'/m.exec(src) || [])[1] || 'unknown';

function literal(name) {
  const start = src.indexOf(`const ${name} = `);
  if (start < 0) throw new Error(`${name} not found`);
  let i = src.indexOf(name === 'MON' ? '{' : '[', start), depth = 0, q = null;
  const open = src[i], close = open === '{' ? '}' : ']';
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    if (q) { if (c === '\\') { j++; continue; } if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') { q = c; continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return src.slice(i, j + 1);
  }
  throw new Error(`${name} not closed`);
}
const run = (code, ctx = {}) => vm.runInNewContext(`(${code})`, { FP: 'img/', IP: '../dragonbound/img/', ...ctx }, { timeout: 1000 });

const MON = run(literal('MON'));
const CHAPTERS = run(literal('CHAPTERS')).map(c => ({ name: c.name, boss: c.boss }));
const LEVELS = run(literal('LEVELS')).map(l => ({ ch: l.ch, name: l.name, bg: l.bg, hz: l.hz }));

const keep = ['name', 'hp', 'atk', 'def', 'h', 'trait', 'w', 'r', 'tip', 'fly', 'boss'];
const mon = Object.fromEntries(Object.entries(MON).map(([k, m]) => [k, Object.fromEntries(keep.filter(f => m[f] !== undefined).map(f => [f, m[f]]))]));
const out = `// GENERATED by tools/sync-db2-data.mjs — do not edit by hand.
// Source: prototype/dragonbound2/index.html (${version}).
export const DB2_MON = ${JSON.stringify(mon)};
export const DB2_CHAPTERS = ${JSON.stringify(CHAPTERS)};
export const DB2_LEVELS = ${JSON.stringify(LEVELS)};
`;
writeFileSync(path.join(here, '../js/data/db2-data.js'), out);
console.log(`db2-data.js: ${Object.keys(mon).length} monstres, ${CHAPTERS.length} chapitres, ${LEVELS.length} niveaux (${version})`);
